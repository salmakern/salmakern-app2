-- s00-019 i Henger igjen-lista - bevisst utsatt av migrasjon 20261029140000 (tett
-- pin_rate_limit_sjekk-hullet) som egen, separat sak:
--
-- Dagens pin_forsok-tabell er nøkkelt på auth.uid() - 5 feil på rad låser DEN
-- anonyme Auth-sesjonen ute i 10 min. SUPA_KEY (den offentlige, publishable
-- nøkkelen) står åpent i appens kildekode på GitHub Pages, så en angriper kan
-- selv opprette nye anonyme Auth-sesjoner i en løkke (hver får sin egen, ferske
-- 5-forsøksgrense) og dermed i praksis prøve alle 10 000 firesifrede PIN-koder
-- uten reell sperre.
--
-- Fiks: en GLOBAL forsøksteller, uavhengig av auth.uid(), på tvers av ALLE
-- anonyme sesjoner samlet. Maks 30 feilede PIN-forsøk totalt per rullerende
-- 10-minutters vindu (uansett hvilken sesjon de kom fra) - deretter avvises ALLE
-- nye PIN-forsøk (ekte ansatte inkludert) til vinduet har rullet videre.
--
-- Terskelen 30/10 min er bevisst satt høyt nok til at normal drift (en håndfull
-- ansatte som av og til taster feil) ikke skal trigge den ved et uhell, men lavt
-- nok til at å gå gjennom alle 10 000 kombinasjoner ville tatt over to døgn
-- sammenhengende - uansett hvor mange nye anonyme sesjoner angriperen oppretter.
-- Rader eldre enn vinduet ryddes bort hver gang sjekken kjører (ingen egen
-- cron-jobb nødvendig). Klienten trenger INGEN endring: feilmeldingen
-- 'FOR_MANGE_FORSOK_GLOBALT' fanges av samme `.includes('FOR_MANGE_FORSOK')`-
-- sjekk som allerede finnes i core.js/ordre-diverse.js.
--
-- IKKE gjort her (bevisst, egen vurdering senere): IP-basert grense for selve
-- anonyme sign-ins (må settes i Supabase Dashboard -> Authentication -> Rate
-- Limits, ikke SQL) og lengre admin-PIN. Se Henger igjen-lista, s00-019.
--
-- Rollback: se supabase/rollback-referanser/global_pin_rate_limit_ROLLBACK.sql

create table if not exists public.pin_global_forsok (
  id bigint generated by default as identity primary key,
  tidspunkt timestamptz not null default now()
);
alter table public.pin_global_forsok enable row level security;
revoke all on public.pin_global_forsok from public, anon, authenticated;

create or replace function public._pin_rate_limit_global_sjekk()
returns void
language plpgsql
security definer
set search_path to 'public'
as $$
declare
  v_antall integer;
begin
  delete from pin_global_forsok where tidspunkt < now() - interval '10 minutes';
  select count(*) into v_antall from pin_global_forsok;
  if v_antall >= 30 then
    raise exception 'FOR_MANGE_FORSOK_GLOBALT';
  end if;
end;
$$;
-- MERK (funnet ved live-verifisering 30.10): "revoke ... from anon, authenticated" ALENE er
-- IKKE nok for en helt NY funksjon - Postgres gir EXECUTE til PUBLIC som standard ved CREATE,
-- og anon/authenticated arver det via PUBLIC uansett. De eksisterende _pin_rate_limit_sjekk/
-- _pin_rate_limit_registrer slapp unna dette kun fordi CREATE OR REPLACE på en funksjon som
-- allerede fantes BEHOLDER dens eksisterende ACL i stedet for å nullstille den - de fikk aldri
-- noen PUBLIC-grant å arve fra i utgangspunktet. Revoke fra public eksplisitt her også.
revoke all on function public._pin_rate_limit_global_sjekk() from public, anon, authenticated;

create or replace function public._pin_rate_limit_global_registrer(v_suksess boolean)
returns void
language plpgsql
security definer
set search_path to 'public'
as $$
begin
  -- Nullstilles bevisst IKKE av en vellykket innlogging (se toppkommentaren) - en
  -- angriper som et uhell lykkes med én PIN skal ikke få et friskt forsøksbudsjett.
  if not v_suksess then
    insert into pin_global_forsok default values;
  end if;
end;
$$;
revoke all on function public._pin_rate_limit_global_registrer(boolean) from public, anon, authenticated;

create or replace function public.logg_inn_med_pin(kandidat_pin text)
returns table(id integer, navn text, rolle text, aktiv boolean, kan_fore_lonn boolean, ansettelsesdato date)
language plpgsql
security definer
set search_path to 'public'
as $function$
declare
  treff ansatte%rowtype;
  ny_token text;
begin
  if auth.uid() is null then
    raise exception 'IKKE_INNLOGGET';
  end if;

  perform public._pin_rate_limit_sjekk();
  perform public._pin_rate_limit_global_sjekk();

  select a.* into treff
  from ansatte a
  join ansatte_pin p on p.ansatt_id = a.id
  where p.pin = kandidat_pin and a.aktiv = true
  limit 1;

  if not found then
    perform public._pin_rate_limit_registrer(false);
    perform public._pin_rate_limit_global_registrer(false);
    return;
  end if;

  perform public._pin_rate_limit_registrer(true);
  perform public._pin_rate_limit_global_registrer(true);

  ny_token := gen_random_uuid()::text;
  update ansatte set session_token = ny_token where ansatte.id = treff.id;

  update auth.users
  set raw_app_meta_data = raw_app_meta_data
    || jsonb_build_object('ansatt_id', treff.id, 'rolle', treff.rolle, 'session_token', ny_token)
  where auth.users.id = auth.uid();

  return query select treff.id, treff.navn, treff.rolle, treff.aktiv, treff.kan_fore_lonn, treff.ansettelsesdato;
end;
$function$;

