--
-- Ny tabell: én rad per gang en ordres status FAKTISK endrer seg (WHEN-betingelsen under
-- hindrer støy fra andre felt-endringer), med tidspunkt og hvilken ansatt (hvis noen) som
-- gjorde det. Gir en ekte tidslinje i stedet for dagens ren tekst-logg (endringer-feltet),
-- og er grunnlaget en fremtidig forhandler-tidslinje i portalen (s08-022/034) kan bygge på
-- når den biten er klar - ingen kobling til portalen er bygget her.

create table if not exists public.ordre_status_historikk (
  id bigint generated by default as identity primary key,
  ordre_id text not null references public.ordrer(id) on delete cascade,
  status text not null,
  ansatt_navn text,
  endret_at timestamptz not null default now()
);
create index if not exists ordre_status_historikk_ordre_id_idx
  on public.ordre_status_historikk (ordre_id, endret_at);

alter table public.ordre_status_historikk enable row level security;
revoke all on public.ordre_status_historikk from public, anon, authenticated;
-- Kun lesing - ingen insert/update/delete-rettighet for klienten i det hele tatt (kun
-- triggeren under, som kjører som postgres og dermed omgår RLS, skriver til tabellen).
grant select on public.ordre_status_historikk to anon, authenticated;
create policy "krever_innlogget_ansatt" on public.ordre_status_historikk for select
  using (exists (select 1 from current_ansatt()));

create or replace function public.ordre_status_historikk_trigger_fn()
returns trigger
language plpgsql
security definer
set search_path to 'public'
as $function$
declare
  v_ansatt_navn text;
begin
  -- Best-effort - en feilende oppslag av hvem som er innlogget (f.eks. et fremtidig
  -- portal-/service-kall uten en vanlig ansatt-sesjon) skal aldri hindre selve
  -- historikk-raden i å bli lagret, og slett ikke rulle tilbake ordre-oppdateringen.
  begin
    select a.navn into v_ansatt_navn
    from public.ansatte a, public.current_ansatt() ca
    where a.id = ca.id;
  exception when others then
    v_ansatt_navn := null;
  end;

  insert into public.ordre_status_historikk (ordre_id, status, ansatt_navn)
  values (new.id, new.ordre_status, v_ansatt_navn);

  return new;
end;
$function$;
revoke all on function public.ordre_status_historikk_trigger_fn() from public, anon, authenticated;

drop trigger if exists "ordre-status-historikk" on public.ordrer;
create trigger "ordre-status-historikk" after update on public.ordrer
  for each row
  when (old.ordre_status is distinct from new.ordre_status)
  execute function public.ordre_status_historikk_trigger_fn();

