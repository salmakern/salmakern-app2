-- Kjørt: 2026-10-30
-- s08-034 (Bestill fase 3: status tilbake til portalen) - Salmakern-siden av outbox-mønsteret.
-- Henrik 30.10: "ja det skal den" (begynn å bygge Salmakern-siden nå).
--
-- Dette er KUN køen (trigger som skriver én rad per faktisk statusendring) - selve
-- utsendingen til Forhandlerportalens endepunkt (cron + HTTP-kall) bygges som et eget steg
-- når portal-siden har et endepunkt klart til å ta imot (trenger avtalt URL + delt
-- hemmelighet, samme mønster som portal-bestilling-funksjonen i motsatt retning). Å bygge
-- køen nå, uavhengig av dette, betyr at ingen statusendringer går tapt/må gjenskapes i
-- etterkant når portal-siden blir klar - køen fylles fra og med nå.
--
-- Separat tabell fra ordre_status_historikk (s09-025, varig logg) - denne er en
-- LEVERINGSKØ (levert/forsøk/siste_feil), ment å tømmes/arkiveres etter hvert, ikke en
-- permanent historikk i seg selv.

create table if not exists public.ordre_status_utboks (
  id bigint generated by default as identity primary key,
  ordre_id text not null references public.ordrer(id) on delete cascade,
  status text not null,
  status_forrige text,
  opprettet_at timestamptz not null default now(),
  levert boolean not null default false,
  levert_at timestamptz,
  forsok integer not null default 0,
  siste_feil text
);
create index if not exists ordre_status_utboks_uleverte_idx
  on public.ordre_status_utboks (opprettet_at) where not levert;

alter table public.ordre_status_utboks enable row level security;
revoke all on public.ordre_status_utboks from public, anon, authenticated;
-- Kun admin kan lese (internt leveringsmekanisme, ikke noe vanlige ansatte trenger å se) -
-- ingen insert/update/delete-rettighet for klienten i det hele tatt.
grant select on public.ordre_status_utboks to anon, authenticated;
create policy "kun_admin_leser" on public.ordre_status_utboks for select
  using (exists (select 1 from current_ansatt() ca where ca.rolle = 'admin'));

create or replace function public.ordre_status_utboks_trigger_fn()
returns trigger
language plpgsql
security definer
set search_path to 'public'
as $function$
begin
  begin
    insert into public.ordre_status_utboks (ordre_id, status, status_forrige)
    values (new.id, new.ordre_status, old.ordre_status);
  exception when others then
    -- Samme prinsipp som de andre ordre-triggerne: en feilende kø-innsetting skal aldri
    -- rulle tilbake selve ordre-oppdateringen.
    raise warning 'ordre-status-utboks: kunne ikke legge i kø (%), ordre-lagringen fortsetter uendret', sqlerrm;
  end;
  return new;
end;
$function$;
revoke all on function public.ordre_status_utboks_trigger_fn() from public, anon, authenticated;

drop trigger if exists "ordre-status-utboks" on public.ordrer;
create trigger "ordre-status-utboks" after update on public.ordrer
  for each row
  when (old.ordre_status is distinct from new.ordre_status)
  execute function public.ordre_status_utboks_trigger_fn();
